-- 005_mensajes.sql: mensajes del formulario de contacto.
-- Los guarda el servidor (POST /api/contacto, con la clave secreta): no hay política de insert
-- para visitantes, así nadie puede escribir directo en la tabla salteando la validación.

create table public.mensajes (
  id bigint generated by default as identity primary key,
  nombre text not null check (char_length(nombre) between 2 and 80),
  email text not null check (char_length(email) between 5 and 120),
  motivo text not null check (motivo in ('elegir', 'pedido', 'envios', 'mayorista', 'otro')),
  mensaje text not null check (char_length(mensaje) between 10 and 2000),
  leido boolean not null default false,
  created_at timestamptz not null default now()
);
create index mensajes_fecha_idx on public.mensajes (created_at desc);

alter table public.mensajes enable row level security;

-- Solo el admin los lee y los marca como leídos
create policy "mensajes: el admin lee" on public.mensajes
  for select to authenticated
  using (public.es_admin());
create policy "mensajes: el admin marca como leído" on public.mensajes
  for update to authenticated
  using (public.es_admin()) with check (public.es_admin());
